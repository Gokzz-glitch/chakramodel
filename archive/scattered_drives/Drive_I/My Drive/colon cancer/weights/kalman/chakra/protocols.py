from typing import Protocol, List, Any
from chakra.types import Detection, Track, PersistentTrack, FrameOutput

class DetectorProtocol(Protocol):
    def detect(self, frame: Any) -> List[Detection]: ...

class TrackerProtocol(Protocol):
    def update(self, detections: List[Detection], frame: Any) -> List[Track]: ...
    def reset(self) -> None: ...

class PersistenceFilterProtocol(Protocol):
    def update(self, tracks: List[Track]) -> List[PersistentTrack]: ...
    def reset(self) -> None: ...

class ConformalCalibratorProtocol(Protocol):
    def annotate(self, tracks: List[PersistentTrack]) -> List[PersistentTrack]: ...

class RendererProtocol(Protocol):
    def render(self, frame: Any, tracks: List[PersistentTrack]) -> Any: ...
