import json
import os
from collections import defaultdict

input_file = r"C:\Users\imgk3\Downloads\scan_results.json"
output_file = r"C:\Users\imgk3\.gemini\antigravity\brain\ed10122d-e091-4566-9916-252437fa3b14\system_wide_inventory.md"

with open(input_file, 'r') as f:
    results = json.load(f)

categories = defaultdict(list)

def categorize(name, path, size):
    name_lower = name.lower()
    ext = os.path.splitext(name_lower)[1]
    
    if ext in ['.pt', '.pth', '.h5', '.onnx']:
        return "Models & Weights"
    elif ext in ['.py', '.ipynb', '.ps1', '.sh', '.yaml', '.yml']:
        return "Code & Notebooks"
    elif ext in ['.md', '.pdf', '.docx', '.txt']:
        return "Documentation & Reports"
    elif ext in ['.csv', '.png', '.jpg', '.jpeg']:
        return "Datasets & Analytics"
    elif ext == '.zip':
        if 'weight' in name_lower or 'best' in name_lower or 'model' in name_lower:
            return "Models & Weights"
        else:
            return "Datasets & Analytics"
    elif 'venv' in path.lower() or '__pycache__' in path.lower() or '.git' in path.lower():
        return "System / Ignored"
    else:
        return "Other / Miscellaneous"

for item in results:
    cat = categorize(item['name'], item['path'], item['size'])
    if cat != "System / Ignored":
        categories[cat].append(item)

# Sort by size (largest first) within categories
for cat in categories:
    categories[cat].sort(key=lambda x: x['size'], reverse=True)

with open(output_file, 'w', encoding='utf-8') as f:
    f.write("# System-Wide ChakraModel File Inventory\n\n")
    f.write(f"Total files matched: **{len(results)}**\n\n")
    
    f.write("> [!NOTE]\n")
    f.write("> This inventory was generated by performing a deep scan across all physical drives (C:\\, D:\\, M:\\). It captures every file related to ChakraModel, polyp detection, and colonoscopy.\n\n")
    
    for cat in sorted(categories.keys()):
        f.write(f"## {cat}\n")
        f.write(f"*{len(categories[cat])} files*\n\n")
        f.write("| File Name | Path | Size (MB) |\n")
        f.write("|---|---|---|\n")
        
        # Limit to top 50 largest per category to avoid massively breaking markdown if thousands
        for i, item in enumerate(categories[cat]):
            if i >= 100:
                f.write(f"| ... and {len(categories[cat]) - 100} more files | | |\n")
                break
            
            size_mb = item['size'] / (1024 * 1024)
            # Create github-style markdown link for the path
            path_uri = item['path'].replace('\\', '/')
            name = item['name']
            
            f.write(f"| [{name}](file:///{path_uri}) | `{item['path']}` | {size_mb:.2f} |\n")
        f.write("\n")

print(f"Inventory generated successfully at {output_file}")
